<?php

declare(strict_types=1);

/**
 * Generates src/Domain/Currency/Iso4217Table.php from the ISO 4217 maintenance agency lists (dev only).
 *
 * Usage: php .scripts/generate-iso4217.php <list-one.xml> <list-three.xml>
 *
 * - list-one.xml: current currencies (code, numeric, minor units). Codes whose minor units are "N.A." are left out.
 * - list-three.xml: historic currencies (code, numeric, withdrawal month). Only codes withdrawn in 1999 or later are
 *   kept (the period a reference-rate feed can cover); the list carries no minor units, so they are 2 unless listed in
 *   HISTORIC_MINOR_UNITS below.
 * - The refused X-codes (precious metals, SDR, units of account, test codes) are never written (contract QC-5);
 *   currencies in the X range such as XAF, XOF, XCD or XPF are kept.
 *
 * The files are read with XMLReader and no entity or DTD loading. Download them by hand and review the diff; the
 * CHANGELOG notes every table update.
 */

/** Refused X-codes (precious metals, SDR and units of account, test and "no currency" codes; contract QC-5). */
const REFUSED_X_CODES = ['XAU', 'XAG', 'XPT', 'XPD', 'XDR', 'XSU', 'XUA', 'XBA', 'XBB', 'XBC', 'XBD', 'XTS', 'XXX', 'XEU', 'XFO', 'XFU', 'XRE', 'XAD'];

const HISTORIC_MINOR_UNITS = [
    'BYR' => 0,
    'ECS' => 0,
    'MGF' => 0,
    'ADP' => 0,
    'BEF' => 0,
    'ESP' => 0,
    'GRD' => 0,
    'ITL' => 0,
    'LUF' => 0,
    'PTE' => 0,
    'TRL' => 0,
    'TPE' => 0,
];

if ($argc !== 3) {
    fwrite(STDERR, "Usage: php .scripts/generate-iso4217.php <list-one.xml> <list-three.xml>\n");
    exit(2);
}

/**
 * @return array{published: string, rows: list<array<string, string>>}
 */
function readList(string $file, string $entry): array
{
    $reader = new XMLReader();
    if (!$reader->open($file, null, LIBXML_NONET | LIBXML_COMPACT)) {
        fwrite(STDERR, "Cannot open {$file}\n");
        exit(1);
    }
    $published = '';
    $rows      = [];
    $row       = null;
    $field     = null;
    while ($reader->read()) {
        if ($reader->nodeType === XMLReader::DOC_TYPE) {
            fwrite(STDERR, "DOCTYPE refused in {$file}\n");
            exit(1);
        }
        if ($reader->nodeType === XMLReader::ELEMENT) {
            if ($reader->name === 'ISO_4217') {
                $published = (string) $reader->getAttribute('Pblshd');
            } elseif ($reader->name === $entry) {
                $row = [];
            } elseif ($row !== null) {
                $field = $reader->name;
            }
        } elseif ($reader->nodeType === XMLReader::TEXT && $row !== null && $field !== null) {
            $row[$field] = trim($reader->value);
        } elseif ($reader->nodeType === XMLReader::END_ELEMENT) {
            if ($reader->name === $entry && $row !== null) {
                $rows[] = $row;
                $row    = null;
            }
            $field = null;
        }
    }
    $reader->close();

    return ['published' => $published, 'rows' => $rows];
}

$current  = readList($argv[1], 'CcyNtry');
$historic = readList($argv[2], 'HstrcCcyNtry');

/** @var array<string, array{0: int, 1: int, 2: bool, 3: string|null}> $table */
$table = [];
foreach ($current['rows'] as $row) {
    $code = $row['Ccy'] ?? '';
    if (preg_match('/^[A-Z]{3}$/', $code) !== 1 || in_array($code, REFUSED_X_CODES, true)) {
        continue;
    }
    $units = $row['CcyMnrUnts'] ?? '';
    if (preg_match('/^\d$/', $units) !== 1) {
        continue;
    }
    $table[$code] = [(int) ($row['CcyNbr'] ?? 0), (int) $units, true, null];
}
foreach ($historic['rows'] as $row) {
    $code = $row['Ccy'] ?? '';
    // A current code always wins over its historic entries.
    if (preg_match('/^[A-Z]{3}$/', $code) !== 1 || in_array($code, REFUSED_X_CODES, true) || ($table[$code][2] ?? false)) {
        continue;
    }
    $withdrawn = $row['WthdrwlDt'] ?? '';
    if (preg_match('/^(\d{4})-(\d{2})$/', $withdrawn, $m) !== 1 || (int) $m[1] < 1999) {
        continue;
    }
    // A code listed several times (withdrawn in several countries) keeps its latest withdrawal (HRK: 2023-01).
    $previous = $table[$code][3] ?? null;
    if ($previous !== null && strcmp($previous, $withdrawn) >= 0) {
        continue;
    }
    $table[$code] = [(int) ($row['CcyNbr'] ?? 0), HISTORIC_MINOR_UNITS[$code] ?? 2, false, $withdrawn];
}
ksort($table);

$lines = [];
foreach ($table as $code => [$numeric, $units, $active, $withdrawn]) {
    $lines[] = sprintf("        '%s' => [%d, %d, %s, %s],", $code, $numeric, $units, $active ? 'true' : 'false', $withdrawn === null ? 'null' : "'" . $withdrawn . "'");
}

